import {
  clearCachedGmailAccessToken,
  ensureGmailAccessToken,
} from './firebase';
import type {
  MedicalHistoryDraft,
  TriageAssessment,
} from '../types/clinical';

export interface PatientEmailCopyPayload {
  fullName: string;
  mrn: string;
  age: number;
  sex: string;
  bloodType: string;
  fingerprintCode: string;
  allergies: string[];
  medications: string[];
  conditions: string[];
  criticalAlerts: string[];
  emergencyContactName: string;
  emergencyContactRelation: string;
  emergencyContactPhone: string;
  dnrStatus: boolean;
  organDonor: boolean;
  histories: MedicalHistoryDraft[];
  latestTriage?: TriageAssessment | null;
}

export interface PatientEmailSections {
  allergiesAndAlerts: boolean;
  medicationsAndConditions: boolean;
  emergencyContact: boolean;
  medicalHistory: boolean;
  latestTriage: boolean;
}

export const DEFAULT_EMAIL_SECTIONS: PatientEmailSections = {
  allergiesAndAlerts: true,
  medicationsAndConditions: true,
  emergencyContact: true,
  medicalHistory: true,
  latestTriage: true,
};

function encodeBase64UrlUtf8(input: string): string {
  const bytes = new TextEncoder().encode(input);
  let binary = '';
  for (let i = 0; i < bytes.length; i += 1) {
    binary += String.fromCharCode(bytes[i]);
  }
  return btoa(binary).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/g, '');
}

function encodeRfc2047Subject(subject: string): string {
  const clean = subject.replace(/[\r\n]+/g, ' ').trim();
  const bytes = new TextEncoder().encode(clean);
  let binary = '';
  for (let i = 0; i < bytes.length; i += 1) {
    binary += String.fromCharCode(bytes[i]);
  }
  return `=?UTF-8?B?${btoa(binary)}?=`;
}

export function formatPatientCopyEmailBody(
  patient: PatientEmailCopyPayload,
  senderEmail: string,
  personalNote?: string,
  sections: PatientEmailSections = DEFAULT_EMAIL_SECTIONS
): { subject: string; bodyText: string } {
  const subject = `MedZex AI Clinical Copy: ${patient.fullName} (${patient.mrn}) · Blood ${patient.bloodType}`;

  const lines: string[] = [
    'MEDZEX AI — PATIENT EMERGENCY & CLINICAL RECORD COPY (READ-ONLY SNAPSHOT)',
    '=========================================================================',
    `Generated By: ${senderEmail}`,
    `Timestamp: ${new Date().toLocaleString()}`,
    '',
  ];

  if (personalNote && personalNote.trim()) {
    lines.push('CLINICAL HANDOFF NOTE:', personalNote.trim(), '');
  }

  let sectionNumber = 1;
  lines.push(
    `${sectionNumber++}. PATIENT IDENTITY & DIRECTIVES`,
    '--------------------------------',
    `Full Name: ${patient.fullName}`,
    `MRN: ${patient.mrn}`,
    `Biometric Print ID: ${patient.fingerprintCode}`,
    `Age / Sex: ${patient.age} yrs / ${patient.sex}`,
    `Blood Type: ${patient.bloodType}`,
    `Code Status: ${patient.dnrStatus ? 'DNR ON FILE' : 'Full Code'}`,
    `Organ Donor: ${patient.organDonor ? 'Yes' : 'No'}`,
    ''
  );

  if (sections.allergiesAndAlerts) {
    lines.push(
      `${sectionNumber++}. SEVERE ALLERGIES & CRITICAL FLAGS`,
      '------------------------------------',
      `Allergies: ${patient.allergies.length > 0 ? patient.allergies.join('; ') : 'None recorded'}`,
      `Critical Alerts: ${patient.criticalAlerts.length > 0 ? patient.criticalAlerts.join('; ') : 'None recorded'}`,
      ''
    );
  }

  if (sections.medicationsAndConditions) {
    lines.push(
      `${sectionNumber++}. ACTIVE MEDICATIONS & CHRONIC CONDITIONS`,
      '------------------------------------------',
      `Active Medications: ${patient.medications.length > 0 ? patient.medications.join('; ') : 'None recorded'}`,
      `Chronic Conditions: ${patient.conditions.length > 0 ? patient.conditions.join('; ') : 'None recorded'}`,
      ''
    );
  }

  if (sections.emergencyContact) {
    lines.push(
      `${sectionNumber++}. EMERGENCY CONTACT`,
      '--------------------',
      `${patient.emergencyContactName} (${patient.emergencyContactRelation})`,
      `Phone: ${patient.emergencyContactPhone}`,
      ''
    );
  }

  if (sections.medicalHistory) {
    lines.push(
      `${sectionNumber++}. PATIENT HISTORICAL CLINICAL DETAILS`,
      '--------------------------------------'
    );
    if (patient.histories.length === 0) {
      lines.push('No historical records attached.');
    } else {
      patient.histories.forEach((entry, idx) => {
        lines.push(
          `${idx + 1}. [${entry.eventDate}] ${entry.category.replace(/_/g, ' ')} — ${entry.title}`
        );
        lines.push(`   Facility: ${entry.facility}${entry.clinician ? ` (${entry.clinician})` : ''}`);
        if (entry.notes) {
          lines.push(`   Notes: ${entry.notes}`);
        }
      });
    }
    lines.push('');
  }

  if (sections.latestTriage && patient.latestTriage) {
    lines.push(
      `${sectionNumber++}. LATEST AI EMERGENCY TRIAGE SUMMARY`,
      '-------------------------------------',
      `ESI Acuity Level: ${patient.latestTriage.esiLevel}`,
      `Vitals: HR ${patient.latestTriage.heartRate} bpm | SpO2 ${patient.latestTriage.spo2}% | BP ${patient.latestTriage.bpSystolic}/${patient.latestTriage.bpDiastolic} | GCS ${patient.latestTriage.gcsScore}/15`,
      `Chief Complaint: ${patient.latestTriage.chiefComplaint}`,
      `Synopsis: ${patient.latestTriage.clinicalSynopsis}`,
      `Contraindications: ${patient.latestTriage.contraindications.length > 0 ? patient.latestTriage.contraindications.join('; ') : 'None flagged'}`,
      `Stabilization Steps: ${patient.latestTriage.immediateActions.join(' -> ')}`,
      ''
    );
  }

  lines.push(
    '---',
    'Read-only clinical snapshot dispatched via MedZex AI. Sending this copy does not alter stored patient records.'
  );

  return {
    subject,
    bodyText: lines.join('\r\n'),
  };
}

export async function sendPatientCopyViaGmail(params: {
  recipientEmail: string;
  senderEmail: string;
  patient: PatientEmailCopyPayload;
  personalNote?: string;
  sections?: PatientEmailSections;
}): Promise<{ messageId: string }> {
  const cleanRecipient = params.recipientEmail.replace(/[\r\n]+/g, '').trim().toLowerCase();
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(cleanRecipient)) {
    throw new Error('Enter a valid recipient Gmail or email address.');
  }

  const accessToken = await ensureGmailAccessToken();
  const { subject, bodyText } = formatPatientCopyEmailBody(
    params.patient,
    params.senderEmail,
    params.personalNote,
    params.sections ?? DEFAULT_EMAIL_SECTIONS
  );

  const mimeMessage = [
    `To: ${cleanRecipient}`,
    `Subject: ${encodeRfc2047Subject(subject)}`,
    'MIME-Version: 1.0',
    'Content-Type: text/plain; charset="UTF-8"',
    'Content-Transfer-Encoding: 8bit',
    '',
    bodyText,
  ].join('\r\n');

  const raw = encodeBase64UrlUtf8(mimeMessage);

  const response = await fetch(
    'https://gmail.googleapis.com/gmail/v1/users/me/messages/send',
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${accessToken}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ raw }),
    }
  );

  if (response.status === 401 || response.status === 403) {
    clearCachedGmailAccessToken();
    const errPayload = await response.json().catch(() => null);
    const reason =
      errPayload?.error?.message ||
      'Gmail authorization expired or was denied. Please confirm again to authorize Gmail send access.';
    throw new Error(reason);
  }

  if (!response.ok) {
    const errPayload = await response.json().catch(() => null);
    throw new Error(errPayload?.error?.message || 'Failed to send patient copy via Gmail API.');
  }

  const data = (await response.json()) as { id?: string };
  return { messageId: data.id || 'sent' };
}
